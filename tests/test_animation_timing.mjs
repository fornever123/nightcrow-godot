import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../tools/battle-editor/package.json',import.meta.url));
const ts=require('typescript');
const timingSource=fs.readFileSync(new URL('../tools/battle-editor/src/core/timing.ts',import.meta.url),'utf8');
const js=ts.transpileModule(timingSource,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {animationDuration,frameStartTime,frameIndexAtTime,frameTimeInCycle,clampMoveFrames,syncTimings}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
let checks=0;
const close=(actual,expected,label)=>{assert.ok(Math.abs(actual-expected)<1e-8,label);checks++;};
const equal=(actual,expected,label)=>{assert.equal(actual,expected,label);checks++;};
const clip={fps:12,frames:[{durationTicks:1},{durationTicks:3},{durationTicks:2}]};
close(animationDuration(clip),0.5,'three unequal frames preserve six ticks');
close(frameStartTime(clip,2),1/3,'third frame begins after the long second frame');
close(animationDuration(clip,2),0.25,'animation speed scales total time');
equal(frameIndexAtTime(clip,0.25),1,'preview holds the long frame');
equal(frameIndexAtTime(clip,1/3),2,'preview switches on the exact boundary');
equal(frameIndexAtTime(clip,0.5),0,'preview loops on the total-time boundary');
equal(frameIndexAtTime(clip,2,1,false),2,'one-shot playback clamps to the last frame');
const loop={...clip,loopFrame:1};
equal(frameIndexAtTime(loop,0.5),1,'loopFrame preserves the introduction');
equal(frameIndexAtTime(loop,0.8),2,'loop repeats only the selected tail');
const legacy={fps:36,frames:[{},{},{}]};
close(animationDuration(legacy),3/36,'old clips keep their original FPS');
equal(frameIndexAtTime(legacy,1/36),1,'old clips keep their original frame selection');
equal(frameIndexAtTime({fps:24,frames:[]},1),0,'empty preview has a stable index');
const move={animation:'test',syncAnimation:true,animationSpeed:2,activeFrameStart:1,activeFrameEnd:1,chainFrame:2};
const config={characters:[{id:'player',sprite:{animations:{test:clip}}}],moves:[move]};
syncTimings(config);
close(move.duration,0.25,'editor move duration matches the imported clip');
close(move.activeStart,1/24,'hit starts on the selected frame');
close(move.activeEnd,4/24,'hit ends after the selected long frame');
close(move.chainOpen,4/24,'chain timing uses the same clock');
close(frameTimeInCycle(clip,0.75),0.25,'second-loop overlay uses the same local time as its character');
close(frameTimeInCycle({...clip,loopFrame:1},0.5),1/12,'loop tail retains its source time origin');
const rebound={activeFrameStart:12,activeFrameEnd:15,chainFrame:19};
clampMoveFrames(rebound,clip);
equal(rebound.activeFrameStart,2,'switching to a shorter clip keeps hit start inside it');
equal(rebound.activeFrameEnd,2,'hit end can use the last source frame');
equal(rebound.chainFrame,3,'chain boundary can follow the last frame');
console.log(`ANIMATION_TIMING_TESTS: ${checks} checks / 0 failures`);
